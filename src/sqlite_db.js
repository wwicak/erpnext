// --- Offline Transactions ---
export async function saveOfflineTransaction(transaction) {
    const db = await getDbInstance();
    const offlineId = transaction.offline_id || `offline-${Date.now()}-${Math.random().toString(36).substr(2, 9)}`;
    const transactionDate = transaction.transaction_date || new Date().toISOString();
    const syncStatus = transaction.sync_status || 'pending';

    // Extract known fields for specific columns, the rest goes into transaction_data
    const {
        customer, pos_profile, company, // Known top-level fields from schema
        // Potentially other fields if the transaction object is flat
        ...details 
    } = transaction;


    const query = `
        INSERT INTO offline_transactions 
        (offline_id, customer, transaction_date, sync_status, pos_profile, company, transaction_data) 
        VALUES (?, ?, ?, ?, ?, ?, ?)
    `;
    // Note: The 'id' (auto-increment) is not part of insert values.
    // 'details' will capture items, payments, totals, etc.
    const result = await db.execute(query, [
        offlineId, transaction.customer, transactionDate, syncStatus,
        transaction.pos_profile, transaction.company, stringifyJSON(details)
    ]);
    return result.lastInsertId; // Return the auto-incremented ID
}

export async function getPendingTransactions() {
    const db = await getDbInstance();
    const results = await db.select("SELECT * FROM offline_transactions WHERE sync_status = 'pending'");
    return results.map(tx => {
        tx.transaction_data = parseJSON(tx.transaction_data, {});
        return tx;
    });
}

