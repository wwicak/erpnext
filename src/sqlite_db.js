// --- Items ---
export async function searchItems(searchTerm) {
    const db = await getDbInstance();
    if (!searchTerm) {
        return await db.select("SELECT * FROM items LIMIT 100");
    }
    const term = `%${searchTerm}%`;
    // Searching barcodes_searchable as a JSON string. This is basic.
    // For more advanced JSON search, SQLite's JSON1 extension would be needed, but LIKE can work for simple cases.
    // Assuming barcodes are stored like '["bc1","bc2"]'
    const barcodeSearchTerm = `%"${searchTerm}"%`; 
    const query = `
        SELECT * FROM items 
        WHERE LOWER(item_name) LIKE LOWER(?) 
           OR LOWER(item_code) LIKE LOWER(?)
           OR barcodes_searchable LIKE ? 
        LIMIT 50
    `;
    return await db.select(query, [term, term, barcodeSearchTerm]);
}

